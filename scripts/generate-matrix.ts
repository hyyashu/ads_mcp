import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { mapTool } from "../inventory/mapping";
import { PLATFORMS, type Platform, loadInventory, validateInventory } from "../src/inventory";
import { type Limitation, ToolRegistry, reconcile } from "../src/mcp/registry";
import { allTools } from "../src/platforms";

const here = (p: string) => fileURLToPath(new URL(p, import.meta.url));
const inv = loadInventory();
const problems = validateInventory(inv);
if (problems.length) throw new Error(`Inventory invalid:\n${problems.join("\n")}`);

const limitations = JSON.parse(readFileSync(here("../inventory/limitations.json"), "utf8")) as Record<string, Limitation>;
const registry = new ToolRegistry(inv).registerAll(allTools());
// Tools proven against a REAL ad account. Empty until live test accounts exist: mocked-API tests do not count.
const liveVerified = new Set(JSON.parse(readFileSync(here("../inventory/live-verified.json"), "utf8")) as string[]);
const rec = reconcile(inv, registry, limitations);
if (rec.errors.length) throw new Error(`Reconciliation failed:\n${rec.errors.join("\n")}`);

const rows = inv.map((t) => {
  const m = mapTool(t);
  const r = rec.rows.find((x) => x.name === t.name)!;
  return { tool: t.name, platform: t.platform, action: t.action_type, ...m, status: r.status, verification: !registry.has(t.name) ? "n/a" : liveVerified.has(t.name) ? "live" : t.platform === "google_ads" ? "schema-checked (v26), not live" : "docs-checked, not live",tests: registry.has(t.name) ? "see src/tests" : "none", inputSchema: registry.has(t.name) ? "defined" : "needs_api_mapping" };
});

const count = <K extends string>(items: { [k in K]: string }[], k: K) => items.reduce<Record<string, number>>((a, x) => ((a[x[k]] = (a[x[k]] ?? 0) + 1), a), {});
const unmapped = rows.filter((r) => r.api.startsWith("UNMAPPED"));
const by = (pred: (r: (typeof rows)[number]) => boolean) => rows.filter(pred).length;

mkdirSync(here("../docs"), { recursive: true });
writeFileSync(here("../docs/tracking.json"), JSON.stringify({ generated_from: "inventory/tool-registry.json", summary: rec.counts, rows }, null, 2));

const esc = (s: string) => s.replace(/\|/g, "\\|");
const table = (list: typeof rows) =>
  ["| Tool | Action | Risk | Domain | Official API surface | Feasibility | Status | Verified |", "|---|---|---|---|---|---|---|---|", ...list.map((r) => `| \`${r.tool}\` | ${r.action} | ${r.risk} | ${r.domain} | ${esc(r.api)} | ${r.feasibility} | ${r.status} | ${r.verification} |`)].join("\n");

const LABEL: Record<Platform, string> = { google_ads: "Google Ads", meta_ads: "Meta Ads", google_search_console: "Search Console", google_analytics: "Google Analytics 4", google_tag_manager: "Tag Manager", bing_webmaster: "Bing Webmaster" };
const statusRow = (title: string, pred: (r: (typeof rows)[number]) => boolean, total: number | string) => `| ${title} | ${PLATFORMS.map((p) => by((r) => r.platform === p && pred(r))).join(" | ")} | ${total} |`;
const flagged = rows.filter((r) => r.feasibility === "limitation_candidate" || r.feasibility === "needs_decision");
const md = `# Implementation tracking matrix

Generated by \`npm run inventory:matrix\` from \`inventory/tool-registry.json\` and the live registry. Do not edit by hand.

## Status

| | ${PLATFORMS.map((p) => LABEL[p]).join(" | ")} | Total |
|---|${PLATFORMS.map(() => "---:").join("|")}|---:|
${statusRow("Inventory", () => true, rows.length)}
${statusRow("**Implemented** (real handler, schemas, tests; see Verified)", (r) => r.status === "implemented", rec.counts.implemented)}
${statusRow("Documented external limitation", (r) => r.status === "external_limitation", rec.counts.external_limitation)}
${statusRow("**Pending** (not exposed by the server)", (r) => r.status === "pending", rec.counts.pending)}

Combined tools (Search Console, GA4 and Tag Manager design, 2026-11-10) are filed under the platform of the account their account_id names: four under Google Ads, one under Meta Ads, the rest under Search Console, GA4 or Tag Manager.

"schema-checked (v26), not live" (Google Ads): tested against fake API responses, and every request it sends in tests (GAQL fields, FROM compatibility, metrics, enum values, mutate bodies) and every fake response row is checked against Google's published v26 REST discovery schema and field reference (inventory/google-ads-v26-*.json); limits are from the v26 guides. It has not run against a real account. "docs-checked, not live" (Meta, Search Console, GA4, Tag Manager): built against the official documentation, tested with fake responses. "live" means proven against a real account.

Only **implemented** tools are listed by the MCP server. A pending tool is never exposed, so there are no stub or fake-success handlers.

## Plan breakdown

- Risk tiers: ${Object.entries(count(rows, "risk")).map(([k, v]) => `${k} ${v}`).join(", ")}
- Feasibility: ${Object.entries(count(rows, "feasibility")).map(([k, v]) => `${k} ${v}`).join(", ")}
- Tools still without an API mapping: ${unmapped.length}

**Caveat:** the "Official API surface" of a pending tool was mapped from knowledge of the API; it is checked against the current documentation (and corrected here if wrong) when the tool is implemented.

## Tools needing a decision before they can be built

These names do not map cleanly onto an official API, or they conflict with the "store only necessary data" rule. They must be resolved (build a reduced, honest form, or document as an external limitation), never faked.

${table(flagged)}

${flagged.map((r) => `- **\`${r.tool}\`**: ${r.notes ?? ""}`).join("\n")}

${PLATFORMS.map((p) => `## ${LABEL[p]} (${by((r) => r.platform === p)})\n\n${table(rows.filter((r) => r.platform === p))}`).join("\n\n")}
`;
writeFileSync(here("../docs/TRACKING.md"), md);
console.log(JSON.stringify({ ...rec.counts, unmapped: unmapped.length, flagged: flagged.length }));
if (unmapped.length) console.log("UNMAPPED:\n" + unmapped.map((r) => `  ${r.platform} ${r.tool}`).join("\n"));
